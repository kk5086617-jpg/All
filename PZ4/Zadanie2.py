import math

def check_series(x, eps=1e-6):
    """
    Вычисляет левую и правую части равенства для sinh(x)
    
    :param x: значение аргумента
    :param eps: заданная погрешность (точность)
    :return: (левая часть, правая часть, число итераций)
    """
    # 1. Вычисление точного значения (левая часть)
    lhs = (math.exp(x) - math.exp(-x)) / 2
    
    # 2. Вычисление суммы ряда (правая часть)
    rhs = 0.0
    term = x  # Первый член ряда при n = 0 (равен x)
    n = 0     # Счетчик итераций (слагаемых)
    
    # Итеративно добавляем члены ряда, пока текущий член по модулю больше eps
    while abs(term) >= eps:
        rhs += term
        n += 1
        # Вычисляем следующий член ряда на основе текущего:
        # term_(n) = term_(n-1) * x^2 / ((2n)*(2n+1))
        term = term * (x ** 2) / ((2 * n) * (2 * n + 1))
        
        # Защита от бесконечного цикла, если ряд начнет расходиться из-за переполнения
        if n > 10000:
            print("Предупреждение: Достигнут лимит итераций!")
            break
            
    return lhs, rhs, n

# --- Демонстрация работы программы при разных значениях x ---
if __name__ == "__main__":
    # Различные значения x для проверки сходимости
    test_values = [0.1, 0.5, 1.0, 3.0, 5.0, -2.0]
    accuracy = 1e-7  # Заданная погрешность epsilon
    
    print(f"Проверка сходимости ряда при точности eps = {accuracy}:")
    print("-" * 80)
    print(f"{'x':>6} | {'Левая часть (LHS)':>18} | {'Правая часть (RHS)':>18} | {'Разность':>12} | {'Итераций (n)':>12}")
    print("-" * 80)
    
    for x_val in test_values:
        exact, approx, iterations = check_series(x_val, accuracy)
        diff = abs(exact - approx)
        print(f"{x_val:>6.1f} | {exact:>18.10f} | {approx:>18.10f} | {diff:>12.2e} | {iterations:>12}")
    print("-" * 80)
